#!/usr/bin/env python3
"""Builds the throwaway design preview and a local preview site (not part of the app or releases).

    python3 -I tools/ui-preview/build.py [--out artifacts/preview] [--no-screenshots] [--serve [PORT]]

Output (git-ignored, under artifacts/):
    index.html            links to everything below
    ui-preview/           the clickable browser preview of the app's flow (this folder's files)
      data.js, data/      real reports for every sample, from the GreyHaven CLI
      tokens.css          colours copied from src/GreyHaven.Presentation/Theming/Palette.cs
      labels.js           wording copied from src/GreyHaven.Core/Hardware/Labels.cs
    reports/              HTML reports for every sample and path
    screenshots/          the real app's UI screenshots from the latest successful CI run on main

Needs the .NET SDK (as for the rest of the repo) and, for screenshots, the GitHub CLI (`gh`),
used through `flatpak-spawn --host` when running inside a Flatpak (e.g. VS Code).
"""
import argparse, html, json, os, re, shutil, socket, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
STATIC = ["index.html", "app.js", "walkthrough.js", "app.css"]

# WCAG 2.1 AA: normal text 4.5:1; borders and other UI parts 3:1.
TEXT_TOKENS = ["text", "textSecondary", "accent", "works", "extraStep", "partial", "unsupported", "unknown"]
SURFACE_TOKENS = ["page", "card", "noticeInfo", "noticeWarning", "commandBackground"]


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, text=True, capture_output=True, cwd=ROOT, **kw).stdout


def dotnet_env():
    env = dict(os.environ)
    local = Path.home() / ".dotnet"
    if (local / "dotnet").exists():
        env.setdefault("DOTNET_ROOT", str(local))
        env["PATH"] = f"{local}:{env.get('PATH', '')}"
    return env


def build_cli(env):
    run(["dotnet", "build", "src/GreyHaven.Cli", "-v", "q", "-nologo"], env=env)
    return ["dotnet", str(ROOT / "src/GreyHaven.Cli/bin/Debug/net10.0/greyhaven.dll")]


def camel(name):
    return name[0].lower() + name[1:]


def palette_tokens():
    """Light and Dark colours from Palette.cs, as CSS custom properties."""
    src = (ROOT / "src/GreyHaven.Presentation/Theming/Palette.cs").read_text()
    themes = {}
    for theme in ("Light", "Dark"):
        block = re.search(rf"public static readonly Palette {theme} = new\((.*?)\);", src, re.S).group(1)
        themes[theme] = dict(re.findall(r'(\w+): Rgb\.Parse\("(#[0-9A-Fa-f]{6})"\)', block))
    def props(t):
        return "".join(f"  --gh-{re.sub(r'(?<!^)(?=[A-Z])', '-', k).lower()}: {v};\n" for k, v in themes[t].items())
    return (
        "/* Generated by tools/ui-preview/build.py from Palette.cs. Do not edit. */\n"
        f":root, :root[data-theme=\"light\"] {{\n{props('Light')}}}\n"
        f":root[data-theme=\"dark\"] {{\n{props('Dark')}}}\n"
        f"@media (prefers-color-scheme: dark) {{ :root:not([data-theme=\"light\"]) {{\n{props('Dark')}}} }}\n"
    )


def _luminance(hex_colour):
    c = [int(hex_colour.lstrip("#")[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast(a, b):
    hi, lo = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def check_brand(palette):
    """Every text colour on every surface, accent buttons and borders. Returns (lowest text ratio, failures)."""
    fails, lowest = [], 99.0
    for t in TEXT_TOKENS:
        for s in SURFACE_TOKENS:
            ratio = contrast(palette[t], palette[s])
            lowest = min(lowest, ratio)
            if ratio < 4.5: fails.append(f"{t} on {s}: {ratio:.2f} (needs 4.5)")
    for a, b, need in [("onAccent", "accent", 4.5), ("cardBorder", "page", 3.0), ("cardBorder", "card", 3.0)]:
        ratio = contrast(palette[a], palette[b])
        if ratio < need: fails.append(f"{a} on {b}: {ratio:.2f} (needs {need})")
    return lowest, fails


def brands_css(brands):
    def kebab(k): return re.sub(r"(?<!^)(?=[A-Z])", "-", k).lower()
    def props(b, mode):
        out = "".join(f"  --gh-{kebab(k)}: {v};\n" for k, v in b["palette"][mode].items())
        out += "".join(f"  --gh-deco-{i + 1}: {v};\n" for i, v in enumerate(b["deco"][mode]))
        if "shadow" in b: out += f"  --gh-shadow-colour: {b['shadow'][mode]};\n"
        return out
    css = "/* Generated by tools/ui-preview/build.py from brands.json. Do not edit. */\n"
    for b in brands:
        fonts = f'  --gh-font-heading: "{b["headingFont"]["family"]}", system-ui, sans-serif;\n  --gh-font-body: "{b["bodyFont"]["family"]}", system-ui, sans-serif;\n'
        css += f':root[data-brand="{b["id"]}"] {{\n{fonts}{props(b, "light")}}}\n'
        css += f':root[data-brand="{b["id"]}"][data-theme="dark"] {{\n{props(b, "dark")}}}\n'
        css += f'@media (prefers-color-scheme: dark) {{ :root[data-brand="{b["id"]}"]:not([data-theme="light"]) {{\n{props(b, "dark")}}} }}\n'
    return css


def labels():
    """The switch-expression label maps from Labels.cs and RatingDisplay.Band, keyed by JSON enum names."""
    out = {}
    for path in ("src/GreyHaven.Core/Hardware/Labels.cs", "src/GreyHaven.Presentation/RatingDisplay.cs"):
        src = (ROOT / path).read_text()
        for m in re.finditer(r"public static string (\w+)\((\w+) \w+\) => \w+ switch\s*\{(.*?)\};", src, re.S):
            method, enum, body = m.groups()
            arms = {camel(member): text for _, member, text in re.findall(r'(?:[\w.]+\.)?(\w+)\.(\w+)(?: or [\w.]+)* => "([^"]*)"', body)}
            default = re.search(r'_ => "([^"]*)"', body)
            if default: arms["_default"] = default.group(1)
            out[f"{method}.{enum}"] = arms
    return "/* Generated by tools/ui-preview/build.py from Labels.cs and RatingDisplay.cs. Do not edit. */\nwindow.GH_LABELS = " + json.dumps(out, indent=1) + ";\n"


def lan_address():
    """This computer's address on the local network (no packets are sent)."""
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.connect(("192.0.2.1", 9))  # TEST-NET-1: never routed, only picks the outgoing interface
        return sock.getsockname()[0]


def gh_command():
    if shutil.which("gh"): return ["gh"]
    if shutil.which("flatpak-spawn"): return ["flatpak-spawn", "--host", "gh"]
    return None


def fetch_screenshots(out):
    gh = gh_command()
    repo = re.search(r'GitHubRepository = "([^"]+)"', (ROOT / "src/GreyHaven.Core/GreyHavenInfo.cs").read_text()).group(1)
    if gh is None:
        print("! gh not found: skipping screenshots", file=sys.stderr)
        return None
    runs = json.loads(run(gh + ["run", "list", "-R", repo, "--workflow", "ci.yml", "--branch", "main", "--status", "success",
                                "--limit", "1", "--json", "databaseId,headSha,createdAt,url"]))
    if not runs:
        print("! no successful CI run on main: skipping screenshots", file=sys.stderr)
        return None
    r = runs[0]
    dest = out / "screenshots"
    shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir(parents=True)
    # The Windows Server 2025 run (Windows 11 generation); older runs named it "ui-screenshots".
    for name in ("ui-screenshots-windows-2025", "ui-screenshots"):
        try:
            run(gh + ["run", "download", str(r["databaseId"]), "-R", repo, "-n", name, "-D", str(dest)])
            break
        except subprocess.CalledProcessError:
            continue
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "artifacts/preview"))
    ap.add_argument("--no-screenshots", action="store_true")
    ap.add_argument("--serve", nargs="?", const=8765, type=int, metavar="PORT")
    ap.add_argument("--lan", action="store_true",
                    help="serve on your local network too, so a phone on the same Wi-Fi can open the QR code's guide")
    args = ap.parse_args()
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)

    env = dotnet_env()
    cli = build_cli(env)
    samples = [s.split()[0] for s in run(cli + ["samples"], env=env).splitlines() if s.strip()]

    # Clickable preview: static files, tokens, labels and real report data.
    ui = out / "ui-preview"
    shutil.rmtree(ui, ignore_errors=True)
    (ui / "data").mkdir(parents=True)
    for f in STATIC: shutil.copy(HERE / f, ui / f)
    (ui / "tokens.css").write_text(palette_tokens())
    (ui / "labels.js").write_text(labels())

    brands = json.loads((HERE / "brands.json").read_text())
    report = []
    for b in brands:
        for mode in ("light", "dark"):
            lowest, fails = check_brand(b["palette"][mode])
            report.append((b["name"], mode, lowest, fails))
    failed = [f"{n} ({m}): {f}" for n, m, _, fs in report for f in fs]
    if failed:
        sys.exit("Brand colours fail WCAG AA:\n  " + "\n  ".join(failed))
    (ui / "brands.css").write_text(brands_css(brands))
    (ui / "brands.js").write_text("/* Generated by tools/ui-preview/build.py. */\nwindow.GH_BRANDS = " + json.dumps(brands) + ";\n")

    reports = out / "reports"
    shutil.rmtree(reports, ignore_errors=True)
    reports.mkdir()
    catalog, reports_by_sample = [], {}
    for s in samples:
        envelope = json.loads(run(cli + ["rate", "--sample", s, "--offline", "--json"], env=env))
        (ui / "data" / f"{s}.json").write_text(json.dumps(envelope))
        reports_by_sample[s] = envelope
        rep = envelope["report"]
        paths = rep["recommendation"]["paths"]
        files = []
        for p in paths:
            kind = p["kind"]
            name = f"{s}-{kind}.html"
            extra = [] if kind == "recommended" else ["--path", kind]
            run(cli + ["rate", "--sample", s, "--offline", *extra, "--out", str(reports / name)], env=env)
            files.append({"kind": kind, "title": p["title"], "file": name, "default": kind == rep["recommendation"].get("defaultPath")})
        catalog.append({"sample": s, "description": rep["profile"].get("description", ""), "reports": files})
    (ui / "data" / "samples.json").write_text(json.dumps(catalog))

    # The walkthrough (Part B): every path and install choice, with its phone guide and QR code.
    pics = ui / "pics"
    pics.mkdir()
    for f in (ROOT / "assets/illustrations").glob("*.svg"): shutil.copy(f, pics / f.name)
    pictures = json.loads((ROOT / "assets/illustrations/catalog.json").read_text())
    phone = ui / "phone"
    phone.mkdir()
    host = lan_address() if args.lan else "localhost"
    port = args.serve or 8765
    journeys = {}
    for s in samples:
        rep = reports_by_sample[s]["report"]
        for p in rep["recommendation"]["paths"]:
            kind = p["kind"]
            for install in ("none", "keep", "replace"):
                name = f"{s}-{kind}-{install}"
                extra = (["--path", kind] if kind in ("easy", "advanced") else []) + ([] if install == "none" else ["--install", install])
                j = json.loads(run(cli + ["rate", "--sample", s, "--offline", *extra, "--journey", "--phone-guide", str(phone / f"{name}.html")], env=env))
                url = f"http://{host}:{port}/ui-preview/phone/{name}.html"
                j["phoneGuide"] = f"phone/{name}.html"
                j["qr"] = {"url": url, "svg": run(cli + ["qr", url], env=env)}
                journeys.setdefault(s, {}).setdefault(kind, {})[install] = j
    # The same data as a script, so the preview is ready on load (and works from file://).
    (ui / "data.js").write_text("/* Generated by tools/ui-preview/build.py. */\nwindow.GH_DATA = "
                                + json.dumps({"samples": catalog, "reports": reports_by_sample, "journeys": journeys, "pictures": pictures}) + ";\n")

    shots = None if args.no_screenshots else fetch_screenshots(out)
    (out / "index.html").write_text(index_page(catalog, shots, out, brands, report))
    print(f"Preview site: {out}")

    if args.serve:
        print(f"Serving on http://localhost:{args.serve}/  (Ctrl+C to stop)")
        if args.lan: print(f"Also on your network at http://{host}:{args.serve}/ - anyone on this Wi-Fi can open the preview while it runs.")
        bind = "0.0.0.0" if args.lan else "127.0.0.1"
        os.execvp(sys.executable, [sys.executable, "-m", "http.server", str(args.serve), "--bind", bind, "--directory", str(out)])


